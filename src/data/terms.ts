function makeTerm(input: TermInput): Term {
  const options = [...distractors[input.category]]
  const answerPosition =
    Array.from(input.id).reduce(
      (total, character) => total + character.charCodeAt(0),
      0,
    ) % 4
  options.splice(answerPosition, 0, input.quizAnswer)

  return {
    ...input,
    scenarioId: input.id,
    quiz: {
      question: `${input.korean}에서 가장 중요한 핵심은 무엇인가요?`,
      options: options as [string, string, string, string],
      answer: input.quizAnswer,
      explanation: `${input.quizAnswer}. 이것이 ${input.korean}을 다른 동작과 구분하는 핵심입니다.`,
    },
  }
}

